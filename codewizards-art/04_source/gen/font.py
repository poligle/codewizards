ORDER = [chr(c) for c in range(32, 127) if chr(c) in G]


def glyph(ch):
    return G.get(ch.upper(), G['?']).split('|')


def draw_text(cv, x, y, text, key, strike=None):
    for n, ch in enumerate(text):
        for j, row in enumerate(glyph(ch)):
            for i, px in enumerate(row):
                if px == '#':
                    cv.set(x + n * 4 + i, y + j, key)
    if strike:
        for xx in range(x - 1, x + len(text) * 4):
            cv.set(xx, y + 2, strike)


def atlas(pal, key='chw'):
    cols = 16
    rows = (len(ORDER) + cols - 1) // cols
    cv = Canvas(cols * 4, rows * 6, pal)
    for n, ch in enumerate(ORDER):
        draw_text(cv, (n % cols) * 4, (n // cols) * 6, ch, key)
    return cv, cols
