"""Builds the room's art: exports the GBC art as palette-indexed RLE data (deterministic, no PNG
encoding) into apps/room/src/assets.gen.js, which index.html loads next to the other scripts. The
page needs no build of its own: the core serves apps/room/src/ and GitHub Pages publishes it as is.

Guild palettes are keyed by the contract's guild ids (the six model makers), plus
`unknown`, the art's free 8th sprite palette (stone greys), for any other id.

Usage:  python3 apps/room/build.py [--check] [--assets-json PATH]
  --check        rebuild in memory and fail if assets.gen.js is out of date (used by CI)
  --assets-json  also write the assets as plain JSON
"""
