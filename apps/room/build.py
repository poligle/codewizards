    G.window_light(lcv)
    c, pos['light'] = cropped(lcv)
    I['light'] = img(c)
    bcv = G.room_canvas(G.GP['anthropic'])
    for side, p in G.LAYOUT['banners']:
        G.banner(bcv, side, p, 'anthropic')
    bcv.outline('K')
    c, pos['banners'] = cropped(bcv)
    I['banners'] = img(c)
    props = []
