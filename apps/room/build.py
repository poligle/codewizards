def hull(points):
    """Convex hull (monotone chain) of 2-D points, counter-clockwise."""
    pts = sorted(set((float(x), float(y)) for x, y in points))
    if len(pts) <= 2:
        return pts
    cross = lambda o, a, b: (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])
    lo, up = [], []
    for p in pts:
        while len(lo) >= 2 and cross(lo[-2], lo[-1], p) <= 0:
            lo.pop()
        lo.append(p)
    for p in reversed(pts):
        while len(up) >= 2 and cross(up[-2], up[-1], p) <= 0:
            up.pop()
        up.append(p)
    return lo[:-1] + up[:-1]


def pixel_font():
    """The interface's pixel font (step 6d): the chalk font's 3 x 5 glyphs (font.py), with Spanish
    accents, as a TrueType font whose pixels are squares. 8 px per em; use it at 16 px (x2) or 24 px."""
    import base64, io
    from fontTools.fontBuilder import FontBuilder
    from fontTools.pens.ttGlyphPen import TTGlyphPen
    import font as F
    P = 125                                     # font units per pixel (1000 per em = 8 px)
    glyphs = {k.upper(): v.split('|') for k, v in F.G.items()}
    marks = {'Á': ('A', '.#.'), 'É': ('E', '.#.'), 'Í': ('I', '.#.'), 'Ó': ('O', '.#.'), 'Ú': ('U', '.#.'),
             'Ñ': ('N', '##.'), 'Ü': ('U', '#.#')}
    for ch, (base, mark) in marks.items():
        if base in glyphs:
            glyphs[ch] = [mark] + glyphs[base]
    names, cmap, gl, adv = ['.notdef', 'space'], {32: 'space'}, {}, {'.notdef': (500, 0), 'space': (375, 0)}
    pen = TTGlyphPen(None)
    gl['.notdef'] = pen.glyph()
    gl['space'] = TTGlyphPen(None).glyph()
    for i, (ch, rows) in enumerate(sorted(glyphs.items())):
        name = f'g{i}'
        pen = TTGlyphPen(None)
        h = len(rows)
        for r, row in enumerate(rows):
            for c, px in enumerate(row):
                if px == '#':
                    x0, y0 = c * P, (h - 1 - r) * P - (0 if h <= 5 else 0)
                    pen.moveTo((x0, y0)); pen.lineTo((x0, y0 + P)); pen.lineTo((x0 + P, y0 + P)); pen.lineTo((x0 + P, y0)); pen.closePath()
        gl[name] = pen.glyph()
        names.append(name)
        adv[name] = (4 * P, 0)
        for cp in {ord(ch), ord(ch.lower())}:
            cmap[cp] = name
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(gl)
    fb.setupHorizontalMetrics(adv)
    fb.setupHorizontalHeader(ascent=7 * P, descent=-2 * P)
    fb.setupNameTable({'familyName': 'CW Pixel', 'styleName': 'Regular'})
    fb.setupOS2(sTypoAscender=7 * P, sTypoDescender=-2 * P, usWinAscent=7 * P, usWinDescent=2 * P)
    fb.setupPost()
    fb.font['head'].created = fb.font['head'].modified = 3846441600   # fixed dates: the same bytes on every build
    buf = io.BytesIO()
    fb.font.recalcTimestamp = False
    fb.save(buf)
    return 'data:font/ttf;base64,' + base64.b64encode(buf.getvalue()).decode('ascii')


def png_uri(cv, scale=1):
    """A canvas as a data: URI (PNG, transparent index 0), scaled by an integer."""
    import base64, io
    import numpy as np
    from PIL import Image
    a = np.zeros((cv.h, cv.w, 4), np.uint8)
    for y in range(cv.h):
        for x in range(cv.w):
            i = cv.a[y, x]
            if i:
                a[y, x, :3] = cv.pal.rgb_of(i)
                a[y, x, 3] = 255
    im = Image.fromarray(a, 'RGBA')
    if scale > 1:
        im = im.resize((cv.w * scale, cv.h * scale), Image.NEAREST)
    buf = io.BytesIO()
    im.save(buf, 'PNG', optimize=True)
    return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode('ascii')


def ui_css():
    """The interface kit (step 6c): stone frames, icons and the wand cursor, in the room's palette."""
    out = ['/* Generated by apps/room/build.py from codewizards-art (art: CC BY 4.0). Do not edit. */']
    out.append('@font-face{font-family:"CW Pixel";src:url(%s) format("truetype");font-display:block}' % pixel_font())
    out.append('.panel{border:16px solid transparent;border-image:url(%s) 8 / 16px stretch;box-shadow:none;image-rendering:pixelated}' % png_uri(G.ui_frame()))
    out.append('.paper-frame{border-image-source:url(%s)}' % png_uri(G.ui_paper()))
    for name in G.ICONS:
        out.append('.ico-%s::before{content:"";display:inline-block;width:16px;height:16px;margin-right:6px;vertical-align:-3px;'
                   'background:url(%s) 0 0/16px 16px no-repeat;image-rendering:pixelated}' % (name, png_uri(G.ui_icon(name))))
    out.append('.tv canvas,button,summary,select,[data-file],[data-room]{cursor:url(%s) 0 0,pointer}' % png_uri(G.ui_cursor(), 2))
    # Step 6e: the scrolls' rod, knobs, parchment and rolled paper, as custom properties for style.css.
    out.append(':root{--rod:url(%s);--knob-l:url(%s);--knob-r:url(%s);--paper:url(%s);--roll:url(%s)}' % (
        png_uri(G.ui_rod()), png_uri(G.ui_knob()), png_uri(G.ui_knob(right=True)), png_uri(G.ui_paper()), png_uri(G.ui_roll())))
    return '\n'.join(out) + '\n'


def plan_js():
    """The room's plan for the engine (world.js), from the art generator: one source of truth."""
    P = G.PLAN
    plan = {
        'w': P['w'], 'd': P['d'], 'blocked': [list(b) for b in P['blocked']],
        'stations': {k: [{'x': x, 'y': y, 'dir': d} for x, y, d in v] for k, v in P['stations'].items()},
        'archi': {'x': P['archi'][0], 'y': P['archi'][1]}, 'door': {'x': P['door'][0], 'y': P['door'][1]},
        'entry': {'x': P['entry'][0], 'y': P['entry'][1]}, 'queue': [{'x': x, 'y': y} for x, y in P['queue']],
    }
    return ('/* Generated by apps/room/build.py from codewizards-art/04_source/gen/gbc.py (PLAN). Do not edit. */\n'
            '(function (G) { (G.CW = G.CW || {}).PLAN = ' + json.dumps(plan, separators=(',', ':')) +
            '; })(typeof globalThis !== \'undefined\' ? globalThis : window);\n')


def bundle(A):
    return HEADER + 'window.CW_ASSETS=' + json.dumps(A, ensure_ascii=False, separators=(',', ':')) + ';\n'



def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--assets-json')
    args = ap.parse_args()
    A = assets()
    if args.assets_json:
        json.dump(A, open(args.assets_json, 'w', encoding='utf-8'), separators=(',', ':'))
    js, pj, uc = bundle(A), plan_js(), ui_css()
    if args.check:
        stale = [n for n, path, txt in (('assets.gen.js', OUT, js), ('plan.gen.js', PLAN_OUT, pj), ('ui.gen.css', UI_OUT, uc))
                 if (open(path, encoding='utf-8').read() if os.path.exists(path) else '') != txt]
        if stale:
            print(f"{' and '.join(stale)} out of date: run python3 apps/room/build.py")
            return 1
        print('assets.gen.js, plan.gen.js and ui.gen.css are up to date')
        return 0
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(js)
    with open(PLAN_OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(pj)
    with open(UI_OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(uc)
    print(f'assets.gen.js: {len(js) // 1024} KB')
    return 0


if __name__ == '__main__':
    sys.exit(main())
