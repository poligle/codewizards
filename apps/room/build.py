    A['potions'] = [{'x': int(x), 'y': int(y), 'c': k} for x, y, k in emitters]
    A['flames'] = [{'x': int(x), 'y': int(y)} for x, y in flames]
    L = G.LAYOUT
    (tx, ty), (px, py) = L['table'], L['pedestal']
