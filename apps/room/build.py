"""Builds the room's art: exports the GBC art as palette-indexed RLE data (deterministic, no PNG
encoding) into apps/room/src/assets.gen.js, which index.html loads next to the other scripts. The
page needs no build of its own: the core serves apps/room/src/ and GitHub Pages publishes it as is.

Guild palettes are keyed by the contract's guild ids (model makers: `google`, not `gemini`), plus
`unknown`, a neutral stone palette taken from the scene's wall colours for any other id.

Usage:  python3 apps/room/build.py [--check] [--assets-json PATH]
  --check        rebuild in memory and fail if assets.gen.js is out of date (used by CI)
  --assets-json  also write the assets as plain JSON
"""
import os
import sys
import json
import base64
import argparse

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, 'codewizards-art', '04_source', 'gen'))
import gbc as G                 # noqa: E402
from core import Canvas, Pal    # noqa: E402

OUT = os.path.join(HERE, 'src', 'assets.gen.js')
HEADER = ('/* Generated by apps/room/build.py from codewizards-art (art: CC BY 4.0, '
          'see codewizards-art/LICENSE). Do not edit. */\n')
# Contract guild id -> art palette (the art keeps its names until step 6 renames it).
CONTRACT_GUILDS = {'anthropic': 'anthropic', 'openai': 'openai', 'google': 'gemini',
                   'deepseek': 'deepseek', 'qwen': 'qwen', 'meta': 'meta'}
NAMES = {'anthropic': 'Anthropic', 'openai': 'OpenAI', 'google': 'Google', 'deepseek': 'DeepSeek',
         'qwen': 'Qwen', 'meta': 'Meta', 'unknown': '?'}
UNKNOWN_EMBLEM = ['.###.', '...#.', '..#..', '.....', '..#..']


def rle(a):
    flat = a.ravel().tolist()
    out = bytearray()
    i, n = 0, len(flat)
    while i < n:
        v, j = flat[i], i + 1
        while j < n and flat[j] == v and j - i < 255:
            j += 1
        out += bytes((v, j - i))
        i = j
    return base64.b64encode(bytes(out)).decode('ascii')


def img(cv):
    return {'w': cv.w, 'h': cv.h, 'rle': rle(cv.a)}


def cropped(cv):
    bb = cv.bbox()
    return cv.crop(bb), [bb[0], bb[1]]


def flame_mirror(n):
    cv = Canvas(3, 5, G.SCENE)
    G._mini(cv, [r[::-1] for r in G.FLAMES[n]], 0, 0, {'x': 'x2', 'y': 'x1', 'z': 'x0'})
    return cv


def assets():
    archi = Pal([('K', G.q555(G.ARCHI[2])), ('M', G.q555(G.ARCHI[1])), ('L', G.q555(G.ARCHI[0]))] +
                [(k, G.q555(c)) for k, c in G.COMMON], 'gbc-archimago')
    wall = [c for _, k, c in G.BGP if k == 'w'][0]          # muro: light, base, dark
    unknown = Pal([('K', G.q555(wall[2])), ('M', G.q555(wall[1])), ('L', G.q555(wall[0]))] +
                  [(k, G.q555(c)) for k, c in G.COMMON], 'gbc-desconocido')
    guilds = {g: [list(c) for c in G.GP[src].rgb] for g, src in CONTRACT_GUILDS.items()}
    guilds['unknown'] = [list(c) for c in unknown.rgb]
    emblems = {g: list(G.EMB[src]) for g, src in CONTRACT_GUILDS.items()}
    emblems['unknown'] = list(UNKNOWN_EMBLEM)
    A = {'v': 2, 'room': {'w': G.CW, 'h': G.CH, 'ox': G.OX, 'oy': G.OY},
         'pal': {'scene': [list(c) for c in G.SCENE.rgb], 'guilds': guilds,
                 'archmage': [list(c) for c in archi.rgb]},
         'scene_keys': list(G.SCENE.keys), 'names': dict(NAMES), 'emblems': emblems,
         'banner_guild': 'anthropic'}
    I, pos = {}, {}
    shell = G.render_room(True)
    G.carpet(shell, *G.LAYOUT['carpet'])
    I['shell'] = img(shell)
    frames, _ = G.door_frames()
    bbs = [f.bbox() for f in frames]
    bb = (min(b[0] for b in bbs), min(b[1] for b in bbs), max(b[2] for b in bbs), max(b[3] for b in bbs))
    I['door'] = [img(f.crop(bb)) for f in frames]
    pos['door'] = [bb[0], bb[1]]
    lcv = G.room_canvas()
    G.window_light(lcv)
    c, pos['light'] = cropped(lcv)
    I['light'] = img(c)
    bcv = G.room_canvas(G.GP['anthropic'])
    for side, p in G.LAYOUT['banners']:
        G.banner(bcv, side, p, 'anthropic')
    bcv.outline('K')
    c, pos['banners'] = cropped(bcv)
    I['banners'] = img(c)
    props = []
    for pid, fn, depth in (('shelfA', lambda cv: G.bookshelf(cv, 0, 1.0), 2.75),
                           ('shelfB', lambda cv: G.bookshelf(cv, 0, 5.25), 7.0),
                           ('table', lambda cv: G.lab_table(cv, 4.5, 3.0), 9.25),
                           ('chair', lambda cv: G.armchair(cv, 8.25, 6.0), 15.25),
                           ('board', lambda cv: G.blackboard(cv, 10.0, 2.0, chalk=False), 12.0)):
        cv = G.room_canvas()
        fn(cv)
        cv.outline('K')
        c, p = cropped(cv)
        props.append({'id': pid, 'depth': depth, 'x': p[0], 'y': p[1], 'img': img(c)})
    A['props'] = props
    sx, sy = G.room_canvas().sp(10.0, 2.0)
    x0, y1 = int(sx) - 15, int(sy) - 8
    A['board'] = {'x': x0 + 3, 'y': y1 - 18 + 3, 'w': 24, 'h': 12}
    torches = []
    for side, p, z in G.LAYOUT['torches']:
        cv = G.room_canvas()
        tx, ty = (cv.sp(0, p, z) if side == 'L' else cv.sp(p, 0, z))
        x = int(tx) - 1 if side == 'L' else int(tx) - 3
        y = int(ty) - 7
        torches.append({'side': side, 'x': x, 'y': y, 'fx': x + 1, 'fy': y - 5, 'hx': x + 2, 'hy': y - 3})
    A['torches'] = torches
    I['torchL'], I['torchR'] = img(G.torch_sprite('L')), img(G.torch_sprite('R'))
    I['flamesL'] = [img(G.flame_sprite(n)) for n in range(3)]
    I['flamesR'] = [img(flame_mirror(n)) for n in range(3)]
    I['halos'] = [img(G.disc(r, 16, 'x1')) for r in (7, 5, 3)]
    wiz = {}
    for rank in ('aprendiz', 'sabio'):
        at = Canvas(16 * 12, 24 * 8, G.GP['anthropic'])
        for r, d in enumerate(G.DIRS):
            for pi, pose in enumerate(('idle', 'walk', 'work')):
                for f in range(4):
                    col = pi * 4 + f
                    at.a[r * 24:(r + 1) * 24, col * 16:(col + 1) * 16] = G.frame('anthropic', d, pose, f, rank).a
        wiz[rank] = img(at)
    I['wizard'] = wiz
    A['orb'] = {d: [(15 - G.ORB[G.MIRROR[d]][0]) if d in G.MIRROR else G.ORB[d][0], G.ORB[G.MIRROR.get(d, d)][1]] for d in G.DIRS}
    A['img'], A['pos'] = I, pos
    return A


def bundle(A):
    return HEADER + 'window.CW_ASSETS=' + json.dumps(A, ensure_ascii=False, separators=(',', ':')) + ';\n'



def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--assets-json')
    args = ap.parse_args()
    A = assets()
    if args.assets_json:
        json.dump(A, open(args.assets_json, 'w', encoding='utf-8'), separators=(',', ':'))
    js = bundle(A)
    if args.check:
        cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if cur != js:
            print('assets.gen.js is out of date: run python3 apps/room/build.py')
            return 1
        print('assets.gen.js is up to date')
        return 0
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(js)
    print(f'assets.gen.js: {len(js) // 1024} KB')
    return 0


if __name__ == '__main__':
    sys.exit(main())
